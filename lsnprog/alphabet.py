"""الأبجدية وترميز النبضات (حسب الورود القرآني + هوفمان) والقيم الأبجدية."""

# ترتيب الحروف الـ29 حسب الورود القرآني (الأكثر وروداً أولاً = الأقل نبضاً).
الحروف = ["ا", "ل", "ن", "م", "و", "ي", "ه", "ر", "ب", "ت", "ك", "ع", "ف", "ق",
           "س", "د", "ذ", "ح", "ء", "ج", "خ", "ش", "ص", "ض", "ز", "ث", "ط", "غ", "ظ"]

# كود هوفمان لكل حرف (0 = سكون، 1 = نبضة).
هوفمان = {
    "ا": "00", "ل": "011", "ن": "1110", "م": "1101", "و": "1100",
    "ي": "1011", "ه": "0100", "ر": "10101", "ب": "10011", "ت": "10010",
    "ك": "10001", "ع": "01011", "ف": "01010", "ق": "111110", "س": "111100",
    "د": "101001", "ذ": "100001", "ح": "1111111", "ء": "1111011", "ج": "1111010",
    "خ": "1000001", "ش": "1000000", "ص": "11111100", "ض": "10100011", "ز": "10100010",
    "ث": "10100001", "ط": "10100000", "غ": "111111011", "ظ": "111111010",
}

# تطبيع الحروف (أ/إ/آ → ا، ة → ه، ى → ي، ؤ/ئ → ء).
تطبيع = {
    "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا",
    "ة": "ه", "ى": "ي", "ؤ": "ء", "ئ": "ء",
}

# القيم الأبجدية (حساب الجُمَّل).
أبجد = {
    "ا": 1, "ب": 2, "ج": 3, "د": 4, "ه": 5, "و": 6, "ز": 7, "ح": 8, "ط": 9,
    "ي": 10, "ك": 20, "ل": 30, "م": 40, "ن": 50, "س": 60, "ع": 70, "ف": 80,
    "ص": 90, "ق": 100, "ر": 200, "ش": 300, "ت": 400, "ث": 500, "خ": 600,
    "ذ": 700, "ض": 800, "ظ": 900, "غ": 1000, "ء": 1,
}


def نبضات(نص):
    """يحوّل النص إلى سلسلة نبضات (0 = سكون، 1 = نبضة)."""
    أكواد = []
    for حرف in نص:
        حرف = تطبيع.get(حرف, حرف)
        if حرف in هوفمان:
            أكواد.append(هوفمان[حرف])
    return " ".join(أكواد)


def أبجدي(نص):
    """يرجع القيمة الأبجدية (حساب الجُمَّل) للنص."""
    مجموع = 0
    for حرف in نص:
        حرف = تطبيع.get(حرف, حرف)
        مجموع += أبجد.get(حرف, 0)
    return مجموع
