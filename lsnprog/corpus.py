"""مستخرج الجذور والسياقات من القرآن + الخريطة المنطقية (ترافق الجذور)."""
import urllib.request
import json
import collections

from .alphabet import نبضات, تطبيع
from . import lexicon

# لواصق تقريبية للاشتقاق (بعد التطبيع).
البادئات = ["وال", "فال", "بال", "كال", "لل", "ال", "و", "ف", "ب", "ك", "ل", "س"]
اللواحق = ["ون", "ين", "ات", "ان", "ها", "هم", "هن", "كم", "كن", "ه", "ة", "ى", "ي", "ا", "و", "ن"]


def تحميل_القرآن():
    """يرجع قائمة الآيات كنصوص خالصة (بلا تشكيل)."""
    url = "https://api.alquran.cloud/v1/quran/quran-simple-clean"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    data = json.loads(urllib.request.urlopen(req, timeout=60).read().decode("utf-8"))
    return [آية["text"] for سورة in data["data"]["surahs"] for آية in سورة["ayahs"]]


def تطبيع_كلمة(كلمة):
    """ينزع التشكيل ويوحّد صور الحروف."""
    محذوف = set(range(0x064B, 0x0660)) | {0x0670, 0x0640} | set(range(0x06D6, 0x06EE))
    نص = "".join(ch for ch in كلمة if ord(ch) not in محذوف)
    return "".join(تطبيع.get(ch, ch) for ch in نص)


def جذر_تقريبي(كلمة):
    """اقتطاع تقريبي للبادئات واللواحق للوصول إلى جذر تقريبي."""
    ك = تطبيع_كلمة(كلمة)
    for ب in البادئات:
        if ك.startswith(ب) and len(ك) - len(ب) >= 3:
            ك = ك[len(ب):]
            break
    for ل in اللواحق:
        if ك.endswith(ل) and len(ك) - len(ل) >= 3:
            ك = ك[:-len(ل)]
            break
    return ك


def فهرس_الجذور(آيات=None):
    """يرجع قاموس جذر ← {التردد، الكلمات} من القرآن (جذور طولها ≥ 3)."""
    if آيات is None:
        آيات = تحميل_القرآن()
    فهرس = collections.defaultdict(collections.Counter)
    for آية in آيات:
        for كلمة in آية.split():
            جذر = جذر_تقريبي(كلمة)
            if len(جذر) >= 3:
                فهرس[جذر][تطبيع_كلمة(كلمة)] += 1
    return {جذر: {"التردد": sum(كلمات.values()), "الكلمات": كلمات}
            for جذر, كلمات in فهرس.items()}


def صورة_رمزية_رقمية(الجذر, الفهرس):
    """الصورة الرمزية الرقمية لجذر: الرمز + المعنى + التردد + النبض + الكلمات."""
    بيانات = الفهرس.get(الجذر)
    if not بيانات:
        return None
    معنى = lexicon.الجذور.get(الجذر, "")
    return {
        "الرمز": الجذر,
        "المعنى": معنى or "(جذر مستخرج — لم يُعرَّف بعد)",
        "التردد": بيانات["التردد"],
        "النبضي": نبضات(الجذر),
        "الكلمات": بيانات["الكلمات"].most_common(6),
    }


def أهم_الجذور(عدد=20):
    """يرجع أهم الجذور (الأكثر وروداً) بصورتها الرمزية الرقمية."""
    فهرس = فهرس_الجذور()
    مرتب = sorted(فهرس.keys(), key=lambda ج: -فهرس[ج]["التردد"])
    return [صورة_رمزية_رقمية(ج, فهرس) for ج in مرتب[:عدد]]


def عرض_أهم_الجذور(عدد=20):
    """يعرض أهم الجذور القرآنية بصورة رمزية رقمية."""
    أسطر = ["=== أهم الجذور القرآنية (الصورة الرمزية الرقمية) ==="]
    for ص in أهم_الجذور(عدد):
        كلمات = "، ".join(f"{ك}({ت})" for ك, ت in ص["الكلمات"])
        أسطر.append(f"«{ص['الرمز']}» — {ص['المعنى']}")
        أسطر.append(f"    تردد={ص['التردد']} · نبض={ص['النبضي']}")
        أسطر.append(f"    كلمات: {كلمات}")
    return "\n".join(أسطر)


def اربط_الجذور_بالمعجم(فهرس, عدد=40):
    """يربط الجذور (المستخرجة من القرآن) بالمعاجم — المعجم البسيط أولاً."""
    مرتب = sorted(فهرس.keys(), key=lambda ج: -فهرس[ج]["التردد"])
    نتيجة = []
    for جذر in مرتب[:عدد]:
        بيانات = فهرس[جذر]
        معنى = lexicon.الجذور.get(جذر, "")
        نتيجة.append({
            "الجذر": جذر,
            "معروف": bool(معنى),
            "المعنى": معنى or "(جذر قرآني جديد — يُعلَّم)",
            "التردد": بيانات["التردد"],
            "كلمات": بيانات["الكلمات"].most_common(4),
        })
    return نتيجة


def جذور_القرآن_المربوطة(عدد=40):
    """يستخرج أهم جذور القرآن ويربطها بالمعاجم."""
    return اربط_الجذور_بالمعجم(فهرس_الجذور(), عدد)


def عرض_الربط_القرآني(عدد=40):
    """يعرض جذور القرآن مرتبطة بالمعجم البسيط (معروف/جديد)."""
    نتائج = جذور_القرآن_المربوطة(عدد)
    معروفة = [ن for ن in نتائج if ن["معروف"]]
    جديدة = [ن for ن in نتائج if not ن["معروف"]]
    أسطر = ["=== جذور القرآن ← المعاجم (المعجم البسيط أولاً) ==="]
    أسطر.append(f"الجذور المعروفة (مربوطة بالمعجم): {len(معروفة)}")
    for ن in معروفة:
        كلمات = "، ".join(f"{ك}({ت})" for ك, ت in ن["كلمات"])
        أسطر.append(f"  «{ن['الجذر']}» — {ن['المعنى']}")
        أسطر.append(f"      تردد={ن['التردد']} · {كلمات}")
    أسطر.append("")
    أسطر.append(f"الجذور الجديدة (تُعلَّم وتُعرَّف): {len(جديدة)}")
    for ن in جديدة:
        كلمات = "، ".join(f"{ك}({ت})" for ك, ت in ن["كلمات"])
        أسطر.append(f"  «{ن['الجذر']}» (تردد={ن['التردد']}) ← {كلمات}")
    return "\n".join(أسطر)


def خريطة_الترافق(آيات=None):
    """الخريطة المنطقية: كلمة ← {كلمة مرافقة: عدد المرات} — كيف تترافق الكلمات في القرآن."""
    if آيات is None:
        آيات = تحميل_القرآن()
    ترافق = collections.defaultdict(collections.Counter)
    for آية in آيات:
        كلمات = {تطبيع_كلمة(ك) for ك in آية.split()}
        for أ in كلمات:
            for ب in كلمات:
                if أ != ب:
                    ترافق[أ][ب] += 1
    return ترافق


def جيران(كلمة, آيات=None, عدد=10):
    """يرجع أكثر الكلمات ترافقاً مع كلمة (اكتشاف العلاقات من القرآن تلقائياً)."""
    ترافق = خريطة_الترافق(آيات)
    return ترافق.get(تطبيع_كلمة(كلمة), collections.Counter()).most_common(عدد)


def أهم_الأزواج(آيات=None, عدد=20):
    """يرجع أكثر أزواج الكلمات ترافقاً في القرآن (أكثر الجذور ترابطاً)."""
    ترافق = خريطة_الترافق(آيات)
    أزواج = collections.Counter()
    for أ, جيران in ترافق.items():
        for ب, ت in جيران.items():
            if أ < ب:
                أزواج[(أ, ب)] = ت
    return أزواج.most_common(عدد)


def عرض_الجيران(كلمة, عدد=10):
    """يعرض الخريطة المنطقية حول كلمة."""
    أسطر = [f"الخريطة المنطقية حول «{كلمة}» (من القرآن):"]
    for ج, ت in جيران(كلمة, عدد=عدد):
        أسطر.append(f"  {ج} ← {ت}")
    return "\n".join(أسطر)


def فهرس_السور():
    """كلمة ← السور (بأسمائها) التي وردت فيها — الطبقة التحليلية للسور."""
    url = "https://api.alquran.cloud/v1/quran/quran-simple-clean"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    data = json.loads(urllib.request.urlopen(req, timeout=60).read().decode("utf-8"))
    فهرس = collections.defaultdict(set)
    for سورة in data["data"]["surahs"]:
        اسم = سورة.get("name", str(سورة["number"]))
        اسم = تطبيع_كلمة(اسم.replace("سُورَةُ", "").strip())
        for آية in سورة["ayahs"]:
            for كلمة in آية["text"].split():
                فهرس[تطبيع_كلمة(كلمة)].add(اسم)
    return {ك: sorted(س) for ك, س in فهرس.items()}


def سور_الكلمة(كلمة):
    """يرجع السور التي وردت فيها كلمة."""
    return فهرس_السور().get(تطبيع_كلمة(كلمة), [])


def عرض_سور(كلمة):
    """يعرض السور التي وردت فيها كلمة (الطبقة التحليلية)."""
    أسطر = [f"«{كلمة}» وردت في السور:"]
    سور = سور_الكلمة(كلمة)
    if سور:
        أسطر.append("  " + " · ".join(سور))
    else:
        أسطر.append("  (لا ورود بهذا اللفظ)")
    return "\n".join(أسطر)
