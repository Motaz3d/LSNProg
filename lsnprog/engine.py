"""محرك الاشتقاق والمعنى والاستنتاج والقراءات والترميز النبضي."""
from .alphabet import نبضات
from . import lexicon


def اشتق(الكلمة):
    """يحلّل الكلمة: جذر + لاحقة ← معنى."""
    بيانات = lexicon.المشتقات.get(الكلمة)
    if not بيانات:
        return None
    الجذر = بيانات["الجذر"]
    اللاحقة = بيانات.get("اللاحقة")
    معنى_الجذر = lexicon.الجذور.get(الجذر, "؟")
    معنى_اللاحقة = lexicon.اللواحق.get(اللاحقة, {}).get("المعنى", "") if اللاحقة else ""
    return {
        "الكلمة": الكلمة,
        "الجذر": الجذر,
        "معنى الجذر": معنى_الجذر,
        "اللاحقة": اللاحقة,
        "معنى اللاحقة": معنى_اللاحقة,
        "المعنى": بيانات["المعنى"],
    }


def معنى(الكلمة, السياق=""):
    """يرجع معاني الكلمة ويختار الأنسب حسب السياق."""
    قائمة = lexicon.المعاني.get(الكلمة)
    if not قائمة:
        return None
    أفضل = None
    أفضل_نقاط = -1
    for معنى_ in قائمة:
        نقاط = sum(1 for مفتاح in معنى_.get("السياق", []) if مفتاح in السياق)
        if نقاط > أفضل_نقاط:
            أفضل_نقاط = نقاط
            أفضل = معنى_
    return {
        "الكلمة": الكلمة,
        "المعاني": [م["المعنى"] for م in قائمة],
        "المعنى المختار": (أفضل or قائمة[0])["المعنى"],
        "السياق": السياق or "(لا سياق)",
    }


def قراءات(الموضع):
    """يعرض القراءات (الفروع الدلالية) لموضع قرآني من أصل واحد."""
    بيانات = lexicon.القراءات.get(الموضع)
    if not بيانات:
        return None
    أسطر = [f"الأصل: الجذر «{بيانات['الجذر']}» ({lexicon.الجذور.get(بيانات['الجذر'], '')})"]
    for قراءة in بيانات["القراءتان"]:
        أسطر.append(f"  {قراءة['اللفظ']} — وزن «{قراءة['الوزن']}» ⇒ {قراءة['المعنى']}")
    أسطر.append(f"  ⇒ {بيانات['الملاحظة']}")
    return أسطر


def استنتاج():
    """عرض استنتاج رمزي بسيط من قواعد الدلالة القرآنية."""
    return [
        "حقيقة: اليد تدل على القوة والقدرة",
        "قاعدة: «فوق» في سياق القوة تدل على السيطرة والتعالي",
        "النص: «يد الله فوق أيديهم»",
        "الاستنتاج: قوة الله وسيطرته فوق قوة البشر",
    ]


def عرض_المثال():
    """يعرض الأمثلة التأسيسية كلها."""
    أسطر = []
    أسطر.append("=== الاشتقاق: من الجذر إلى المعنى ===")
    for كلمة in ["قرآن", "رحمن", "عمران", "حيان", "سفيان"]:
        ن = اشتق(كلمة)
        أسطر.append(f"{كلمة} ← جذر «{ن['الجذر']}» ({ن['معنى الجذر']})")
        أسطر.append(f"    + لاحقة «{ن['اللاحقة']}» ({ن['معنى اللاحقة']})")
        أسطر.append(f"    ⇒ {ن['المعنى']}")
    أسطر.append("")
    أسطر.append("=== تعدد المعنى والسياق ===")
    for كلمة, سياق in [("يد", "يد الله فوق أيديهم"), ("فوق", "يد الله فوق أيديهم")]:
        ن = معنى(كلمة, سياق)
        أسطر.append(f"«{كلمة}» معانيها: {'، '.join(ن['المعاني'])}")
        أسطر.append(f"    في «{سياق}» ⇒ {ن['المعنى المختار']}")
    أسطر.append("")
    أسطر.append("=== القراءات (فروع من أصل واحد) ===")
    أسطر.extend(قراءات("يوم الدين"))
    أسطر.append("")
    أسطر.append("=== الاستنتاج ===")
    أسطر.extend(استنتاج())
    أسطر.append("")
    أسطر.append("=== النبضات (0 = سكون، 1 = نبضة) ===")
    أسطر.append(f"«قرآن» ⇒ {نبضات('قرآن')}")
    return "\n".join(أسطر)
