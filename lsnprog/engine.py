"""محرك الاشتقاق والمعنى والاستنتاج والقراءات والرمز-الرقم والترميز النبضي."""
from .alphabet import نبضات
from . import lexicon


def اشتق(الكلمة):
    """يحلّل الكلمة: جذر + لاحقة ← معنى."""
    بيانات = lexicon.المشتقات.get(الكلمة)
    if not بيانات:
        return None
    الجذر = بيانات["الجذر"]
    اللاحقة = بيانات.get("اللاحقة")
    معنى_الجذر = lexicon.الجذور.get(الجذر, "؟")
    معنى_اللاحقة = lexicon.اللواحق.get(اللاحقة, {}).get("المعنى", "") if اللاحقة else ""
    return {
        "الكلمة": الكلمة,
        "الجذر": الجذر,
        "معنى الجذر": معنى_الجذر,
        "اللاحقة": اللاحقة,
        "معنى اللاحقة": معنى_اللاحقة,
        "المعنى": بيانات["المعنى"],
    }


def رمزي_رقمي(الكلمة):
    """يدمج الرمز (الكلمة/الجذر/المعنى) والرقم (النبضات) في تمثيل واحد."""
    ن = اشتق(الكلمة)
    if not ن:
        return None
    return {
        "الرمز": ن["الكلمة"],
        "الجذر": ن["الجذر"],
        "المعنى": ن["المعنى"],
        "الرقم": نبضات(الكلمة),
    }


def معنى(الكلمة, السياق=""):
    """يرجع معاني الكلمة ويختار الأنسب حسب السياق."""
    قائمة = lexicon.المعاني.get(الكلمة)
    if not قائمة:
        return None
    أفضل = None
    أفضل_نقاط = -1
    for معنى_ in قائمة:
        نقاط = sum(1 for مفتاح in معنى_.get("السياق", []) if مفتاح in السياق)
        if نقاط > أفضل_نقاط:
            أفضل_نقاط = نقاط
            أفضل = معنى_
    return {
        "الكلمة": الكلمة,
        "المعاني": [م["المعنى"] for م in قائمة],
        "المعنى المختار": (أفضل or قائمة[0])["المعنى"],
        "السياق": السياق or "(لا سياق)",
    }


def قراءات(الموضع):
    """يعرض القراءات (الفروع الدلالية) لموضع قرآني من أصل واحد."""
    بيانات = lexicon.القراءات.get(الموضع)
    if not بيانات:
        return None
    أسطر = [f"الأصل: الجذر «{بيانات['الجذر']}» ({lexicon.الجذور.get(بيانات['الجذر'], '')})"]
    for قراءة in بيانات["القراءتان"]:
        أسطر.append(f"  {قراءة['اللفظ']} — وزن «{قراءة['الوزن']}» ⇒ {قراءة['المعنى']}")
    أسطر.append(f"  ⇒ {بيانات['الملاحظة']}")
    return أسطر


def علاقة(الموضع):
    """يعرض علاقة منطقية/اشتقاقية بين كلمتين من أصل واحد."""
    return lexicon.العلاقات.get(الموضع)


def استنتاج():
    """عرض استنتاج رمزي بسيط من قواعد الدلالة القرآنية."""
    return [
        "حقيقة: اليد تدل على القوة والقدرة",
        "قاعدة: «فوق» في سياق القوة تدل على السيطرة والتعالي",
        "النص: «يد الله فوق أيديهم»",
        "الاستنتاج: قوة الله وسيطرته فوق قوة البشر",
    ]


def _أسطر_اشتقاق(الكلمة):
    ن = اشتق(الكلمة)
    أسطر = [f"{الكلمة} ← جذر «{ن['الجذر']}» ({ن['معنى الجذر']})"]
    if ن["اللاحقة"]:
        أسطر.append(f"    + لاحقة «{ن['اللاحقة']}» ({ن['معنى اللاحقة']})")
    أسطر.append(f"    ⇒ {ن['المعنى']}")
    return أسطر


def عرض_المثال():
    """يعرض الأمثلة التأسيسية كلها."""
    أسطر = []
    أسطر.append("=== الاشتقاق (لاحقة «ان» = الوفرة) ===")
    for كلمة in ["قرآن", "رحمن", "عمران", "حيان", "سفيان"]:
        أسطر.extend(_أسطر_اشتقاق(كلمة))
    أسطر.append("")
    أسطر.append("=== الأصل والفروع: الجذور المتشابكة ===")
    أسطر.extend(_أسطر_اشتقاق("شجرة"))
    أسطر.extend(_أسطر_اشتقاق("شجار"))
    أسطر.append("")
    أسطر.append("=== لاحقة «ون» (التكثير والتمدد) ===")
    أسطر.extend(_أسطر_اشتقاق("فرعون"))
    أسطر.append("")
    أسطر.append("=== الجذر «موس» (القطع) ===")
    أسطر.extend(_أسطر_اشتقاق("موسى"))
    أسطر.append("")
    أسطر.append("=== كلمة الله (النقاء بلا إضافة) ===")
    أسطر.extend(_أسطر_اشتقاق("عيسى"))
    أسطر.extend(_أسطر_اشتقاق("المسيح"))
    أسطر.extend(_أسطر_اشتقاق("كلمة"))
    أسطر.append(علاقة("عيسى كلمة الله"))
    أسطر.append("")
    أسطر.append("=== الرمز والرقم (الدمج) ===")
    for كلمة in ["شجرة", "فرعون", "موسى", "عيسى"]:
        ن = رمزي_رقمي(كلمة)
        أسطر.append(f"الرمز «{ن['الرمز']}» (جذر {ن['الجذر']}) = الرقم {ن['الرقم']}")
    أسطر.append("")
    أسطر.append("=== تعدد المعنى والسياق ===")
    for كلمة, سياق in [("يد", "يد الله فوق أيديهم"), ("فوق", "يد الله فوق أيديهم")]:
        ن = معنى(كلمة, سياق)
        أسطر.append(f"«{كلمة}» معانيها: {'، '.join(ن['المعاني'])}")
        أسطر.append(f"    في «{سياق}» ⇒ {ن['المعنى المختار']}")
    أسطر.append("")
    أسطر.append("=== القراءات (فروع من أصل واحد) ===")
    أسطر.extend(قراءات("يوم الدين"))
    أسطر.append("")
    أسطر.append("=== العلاقات (الرمزية المنطقية) ===")
    أسطر.append(علاقة("موسى يقطع فرعون"))
    أسطر.append("")
    أسطر.append("=== الاستنتاج ===")
    أسطر.extend(استنتاج())
    return "\n".join(أسطر)
