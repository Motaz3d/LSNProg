"""شبكة رمزية-عصبية: عقد (مفاهيم/خلايا) وروابط (علاقات/مشابك) مع انتشار التنشيط.

الفكرة: «الرقمية» هنا كالخلايا العصبية — كل مفهوم خلية، وكل علاقة مشبك،
والسؤال يجرّد إلى مفاهيم منشَّطة ينتشر تنشيطها عبر الروابط ليصل إلى استنتاجات.
"""
from . import lexicon


class شبكة:
    def __init__(self):
        self.العقد = {}    # اسم → {"معنى": str, "وزن": float}
        self.الروابط = []  # (أ، علاقة، ب، وزن)

    def عقدة(self, اسم, معنى, وزن=1.0):
        self.العقد[اسم] = {"معنى": معنى, "وزن": وزن}

    def رابط(self, أ, علاقة, ب, وزن=1.0):
        self.الروابط.append((أ, علاقة, ب, وزن))

    def استعلام(self, نص, خطوات=3, تسرب=0.5):
        """يجرّد السؤال، ينشّط المفاهيم المطابقة، ينشر التنشيط، ويرجع الاستنتاجات مرتبة."""
        كلمات = نص.split()
        تنشيط = {}
        for اسم, بيانات in self.العقد.items():
            قيمة = 0.0
            for كلمة in كلمات:
                if كلمة and (كلمة in اسم or اسم in كلمة):
                    قيمة += بيانات["وزن"]
            if قيمة > 0:
                تنشيط[اسم] = قيمة

        for _ in range(خطوات):
            جديد = dict(تنشيط)
            for أ, _, ب, وزن in self.الروابط:
                if أ in تنشيط:
                    جديد[ب] = جديد.get(ب, 0.0) + تنشيط[أ] * وزن * تسرب
                if ب in تنشيط:
                    جديد[أ] = جديد.get(أ, 0.0) + تنشيط[ب] * وزن * تسرب
            تنشيط = جديد

        مرتب = sorted(تنشيط.items(), key=lambda زوج: -زوج[1])
        return [(اسم, round(قيمة, 3), self.العقد[اسم]["معنى"])
                for اسم, قيمة in مرتب if قيمة > 0.001]


def بناء_الشبكة():
    """يبني الشبكة من المعجم + روابط دلالية مستخلصة من فهم القرآن."""
    ش = شبكة()

    # عقد الجذور (وزن أعلى = مفهوم جوهري).
    for جذر, معنى in lexicon.الجذور.items():
        ش.عقدة(جذر, معنى, وزن=2.0)

    # عقد المشتقات + روابط الاشتقاق.
    for كلمة, بيانات in lexicon.المشتقات.items():
        ش.عقدة(كلمة, بيانات["المعنى"], وزن=1.0)
        if بيانات["الجذر"] in lexicon.الجذور:
            ش.رابط(بيانات["الجذر"], "اشتقاق", كلمة, 1.0)

    # عقد المعاني المتعددة + روابطها.
    for كلمة, قائمة in lexicon.المعاني.items():
        for م in قائمة:
            معنى = م["المعنى"]
            ش.عقدة(معنى, معنى, وزن=0.6)
            ش.رابط(كلمة, "معنى", معنى, 0.8)

    # مفاهيم إضافية.
    إضافية = {
        "قطع": "القطع والحسم",
        "جبر": "الجبر والقهر والإجبار",
        "كلمة الله": "القول النقي بلا إضافات",
    }
    for اسم, معنى in إضافية.items():
        ش.عقدة(اسم, معنى, وزن=0.8)

    # روابط دلالية (من فهم القرآن والاشتقاق).
    روابط = [
        ("موسى", "يقطع", "فرعون", 1.0),
        ("موسى", "يعني", "قطع", 0.9),
        ("عيسى", "هو", "كلمة الله", 1.0),
        ("عيسى", "هو", "المسيح", 0.9),
        ("شجرة", "من جذر", "شجار", 0.8),
        ("يد", "تدل على", "القوة والقدرة والسلطان", 0.9),
        ("فوق", "تدل على", "السيطرة والتعالي والقهر", 0.8),
        ("سلطان", "يتضمن", "ملك", 0.7),
        ("سلطان", "من", "جبر", 0.9),
    ]
    for أ, علاقة, ب, وزن in روابط:
        if أ not in ش.العقد:
            ش.عقدة(أ, أ, 1.0)
        if ب not in ش.العقد:
            ش.عقدة(ب, ب, 1.0)
        ش.رابط(أ, علاقة, ب, وزن)

    return ش


def عرض_استعلام(أسئلة=None):
    """يجرّب الشبكة على أسئلة ويعرض الاستنتاجات (النموذج المحلي)."""
    ش = بناء_الشبكة()
    if أسئلة is None:
        أسئلة = [
            "من يقطع فرعون",
            "ما معنى عيسى",
            "يد الله فوق أيديهم",
            "من يتضمن السلطان",
        ]
    أسطر = []
    for سؤال in أسئلة:
        أسطر.append(f"سؤال: «{سؤال}»")
        for اسم, قيمة, معنى in ش.استعلام(سؤال):
            أسطر.append(f"    {اسم} ({قيمة}) ← {معنى}")
        أسطر.append("")
    return "\n".join(أسطر)
