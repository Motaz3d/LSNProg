"""شبكة رمزية-عصبية: عقد (مفاهيم/خلايا) وروابط (علاقات/مشابك) مع انتشار التنشيط.

الفكرة: «الرقمية» هنا كالخلايا العصبية — كل مفهوم خلية، وكل علاقة مشبك،
والسؤال يجرّد إلى مفاهيم منشَّطة ينتشر تنشيطها عبر الروابط ليصل إلى استنتاجات.

منهج النموذج: **التمعّن** في الجذر واللواحق والبدايات للوصول إلى المعنى.
"""
from . import lexicon


class شبكة:
    def __init__(self):
        self.العقد = {}    # اسم → {"معنى": str, "وزن": float}
        self.الروابط = []  # (أ، علاقة، ب، وزن)

    def عقدة(self, اسم, معنى, وزن=1.0):
        self.العقد[اسم] = {"معنى": معنى, "وزن": وزن}

    def رابط(self, أ, علاقة, ب, وزن=1.0):
        self.الروابط.append((أ, علاقة, ب, وزن))

    def استعلام(self, نص, خطوات=3, تسرب=0.5):
        """يجرّد السؤال، ينشّط المفاهيم المطابقة، ينشر التنشيط، ويرجع الاستنتاجات مرتبة."""
        كلمات = نص.split()
        تنشيط = {}

        def نظيف(س):
            س = س.strip()
            if س.startswith("و") and len(س) > 3:
                س = س[1:]
            if س.startswith("ال") and len(س) > 3:
                س = س[2:]
            return س

        # خريطة الكلمة ← جذرها (المطابقة بالجذر والفروع، لا بالحرف).
        from . import learned
        جذور = {}
        for جذر in lexicon.الجذور:
            جذور[جذر] = جذر
        for كلمة, ب in lexicon.المشتقات.items():
            جذور[كلمة] = ب.get("الجذر", كلمة)
        for جذر, _, مشتقات in learned.جذور_جديدة:
            جذور[جذر] = جذر
            for كلمة, _ in مشتقات:
                جذور[كلمة] = جذر
        for جذر, مشتقات in learned.كلمات_مضافة:
            for كلمة, _ in مشتقات:
                جذور[كلمة] = جذر
        for اسم, _ in learned.مفاهيم:
            جذور[اسم] = اسم

        def مفتاح(س):
            س = نظيف(س)
            return جذور.get(س, س)

        for اسم, بيانات in self.العقد.items():
            قيمة = 0.0
            for كلمة in كلمات:
                if كلمة and (كلمة == اسم or نظيف(كلمة) == نظيف(اسم) or مفتاح(كلمة) == مفتاح(اسم)):
                    قيمة += بيانات["وزن"]
            if قيمة > 0:
                تنشيط[اسم] = قيمة

        for _ in range(خطوات):
            جديد = dict(تنشيط)
            for أ, _, ب, وزن in self.الروابط:
                if أ in تنشيط:
                    جديد[ب] = جديد.get(ب, 0.0) + تنشيط[أ] * وزن * تسرب
                if ب in تنشيط:
                    جديد[أ] = جديد.get(أ, 0.0) + تنشيط[ب] * وزن * تسرب
            تنشيط = جديد

        مرتب = sorted(تنشيط.items(), key=lambda زوج: -زوج[1])
        return [(اسم, round(قيمة, 3), self.العقد[اسم]["معنى"])
                for اسم, قيمة in مرتب if قيمة > 0.001]


def بناء_الشبكة():
    """يبني الشبكة من المعجم + روابط دلالية مستخلصة من التمعّن في الجذور."""
    ش = شبكة()

    # عقد الجذور (وزن أعلى = مفهوم جوهري).
    for جذر, معنى in lexicon.الجذور.items():
        ش.عقدة(جذر, معنى, وزن=2.0)

    # عقد المشتقات + روابط الاشتقاق.
    for كلمة, بيانات in lexicon.المشتقات.items():
        ش.عقدة(كلمة, بيانات["المعنى"], وزن=1.0)
        if بيانات["الجذر"] in lexicon.الجذور:
            ش.رابط(بيانات["الجذر"], "اشتقاق", كلمة, 1.0)

    # عقد المعاني المتعددة + روابطها.
    for كلمة, قائمة in lexicon.المعاني.items():
        for م in قائمة:
            معنى = م["المعنى"]
            ش.عقدة(معنى, معنى, وزن=0.6)
            ش.رابط(كلمة, "معنى", معنى, 0.8)

    # مفاهيم إضافية.
    إضافية = {
        "قطع": "القطع والحسم",
        "جبر": "الجبر والقهر والإجبار",
        "كلمة الله": "القول النقي بلا إضافات",
        "القوة القاهرة": "السلطة الغالبة القاهرة",
        "الملكية": "التملّك والتصرف",
        "ضوء في الظلام": "الضياء وسط العتمة",
    }
    for اسم, معنى in إضافية.items():
        ش.عقدة(اسم, معنى, وزن=0.8)

    # روابط دلالية (من التمعّن في الجذور والاشتقاق).
    روابط = [
        ("موسى", "يقطع", "فرعون", 1.0),
        ("موسى", "يعني", "قطع", 0.9),
        ("عيسى", "هو", "كلمة الله", 1.0),
        ("عيسى", "هو", "المسيح", 0.9),
        ("شجرة", "من جذر", "شجار", 0.8),
        ("يد", "تدل على", "القوة والقدرة والسلطان", 0.9),
        ("فوق", "تدل على", "السيطرة والتعالي والقهر", 0.8),
        ("سلطان", "جوهره", "القوة القاهرة", 1.0),
        ("سلطان", "من", "جبر", 0.9),
        ("سلطان", "يتضمن", "ملك", 0.7),
        ("ملك", "جوهره", "الملكية", 0.9),
        ("كاميرا", "من", "قمرة", 1.0),
        ("قمرة", "من جذر", "قمر", 0.9),
        ("قمر", "هو", "ضوء في الظلام", 0.9),
    ]
    for أ, علاقة, ب, وزن in روابط:
        if أ not in ش.العقد:
            ش.عقدة(أ, أ, 1.0)
        if ب not in ش.العقد:
            ش.عقدة(ب, ب, 1.0)
        ش.رابط(أ, علاقة, ب, وزن)

    # المفاهيم المتعلَّمة (مُثبَّتة في الشبكة الأساسية).
    from . import learned
    for جذر, معنى, مشتقات in learned.جذور_جديدة:
        علّم_جذر(ش, جذر, معنى, مشتقات)
    for جذر, مشتقات in learned.كلمات_مضافة:
        for كلمة, معنى in مشتقات:
            ش.عقدة(كلمة, معنى, وزن=1.0)
            ش.رابط(جذر, "اشتقاق", كلمة, 1.0)
    for أ, علاقة, ب, وزن in learned.روابط:
        علّم_رابط(ش, أ, علاقة, ب, وزن)
    for اسم, معنى in learned.مفاهيم:
        if اسم not in ش.العقد:
            ش.عقدة(اسم, معنى, وزن=0.8)

    return ش


def عرض_استعلام(أسئلة=None):
    """يجرّب الشبكة على أسئلة ويعرض الاستنتاجات (النموذج المحلي القائم على التمعّن)."""
    ش = بناء_الشبكة()
    if أسئلة is None:
        أسئلة = [
            "من يقطع فرعون",
            "ما معنى عيسى",
            "يد الله فوق أيديهم",
            "ما الفرق بين سلطان وملك",
            "ما هي الكاميرا",
        ]
    أسطر = []
    for سؤال in أسئلة:
        أسطر.append(f"سؤال: «{سؤال}»")
        for اسم, قيمة, معنى in ش.استعلام(سؤال):
            أسطر.append(f"    {اسم} ({قيمة}) ← {معنى}")
        أسطر.append("")
    return "\n".join(أسطر)


def علّم_جذر(ش, الجذر, المعنى, المشتقات):
    """يعلّم الشبكة جذراً جديداً ومشتقاته (تعلّم من الأشياء الجديدة)."""
    ش.عقدة(الجذر, المعنى, وزن=2.0)
    for كلمة, معنى in المشتقات:
        ش.عقدة(كلمة, معنى, وزن=1.0)
        ش.رابط(الجذر, "اشتقاق", كلمة, 1.0)


def علّم_رابط(ش, أ, علاقة, ب, وزن=1.0):
    """يعلّم الشبكة رابطاً جديداً بين مفهومين."""
    for اسم in (أ, ب):
        if اسم not in ش.العقد:
            ش.عقدة(اسم, اسم, 1.0)
    ش.رابط(أ, علاقة, ب, وزن)


def عرض_تعلم():
    """يعرض قدرة النموذج على التعلّم من مثال قرآني جديد (الدنيا/الآخرة)."""
    ش = بناء_الشبكة()
    أسطر = ["=== قبل التعليم (لا يعرف) ==="]
    أسطر.append("سؤال: «ما معنى الدنيا»")
    قبل = ش.استعلام("ما معنى الدنيا")
    if not قبل:
        أسطر.append("    (لا نتيجة — النموذج لا يعرف «الدنيا» بعد)")
    else:
        for اسم, قيمة, معنى in قبل:
            أسطر.append(f"    {اسم} ({قيمة}) ← {معنى}")

    أسطر.append("")
    أسطر.append("=== التعليم (من القرآن) ===")
    علّم_جذر(ش, "دنو", "الدنو والقرب", [
        ("الدنيا", "الحياة الدانية القريبة (العاجلة)"),
        ("دانية", "قريبة"),
    ])
    علّم_جذر(ش, "أخر", "التأخر والبعد", [
        ("الآخرة", "الحياة المتأخرة (الآجلة)"),
    ])
    علّم_رابط(ش, "الدنيا", "تقابل", "الآخرة", 1.0)
    أسطر.append("عُلِّم: دنو (القرب) ← الدنيا · أخر (التأخر) ← الآخرة · ورابط تقابل بينهما")

    أسطر.append("")
    أسطر.append("=== بعد التعليم (يعرف ويستنتج) ===")
    for سؤال in ["ما معنى الدنيا", "ما معنى الآخرة", "ما علاقة الدنيا والآخرة"]:
        أسطر.append(f"سؤال: «{سؤال}»")
        for اسم, قيمة, معنى in ش.استعلام(سؤال):
            أسطر.append(f"    {اسم} ({قيمة}) ← {معنى}")
        أسطر.append("")
    return "\n".join(أسطر)


