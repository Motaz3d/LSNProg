def شرح(نص, ش=None):
    """المنهج الموحّد للإجابة: يستخلص المعنى والفكرة ويقدّمها منطقياً (لا عرضاً مجرداً)."""
    if ش is None:
        ش = بناء_الشبكة()
    نتائج = ش.استعلام(نص)
    if not نتائج:
        return "لا أعرف هذا بعد — علّمني الجذر والمعنى وسأربطه بالقرآن والمعاجم."
    أسطر = [f"«{نص}»", ""]
    أسطر.append("المعنى:")
    for اسم, قيمة, معنى in نتائج[:3]:
        أسطر.append(f"  • {اسم} — {معنى}")
    أصل = نتائج[0][0]
    علاقات = [(ع, ب) for أ, ع, ب, _ in ش.الروابط if أ == أصل and ب in ش.العقد]
    if علاقات:
        أسطر.append("")
        أسطر.append("الفكرة:")
        for ع, ب in علاقات:
            أسطر.append(f"  • {أصل} {ع} {ب} — {ش.العقد[ب]['معنى']}")
    return "\n".join(أسطر)
