#!/usr/bin/env python3
"""واجهة سطر أوامر للغة لسن (LSNProg)."""
from lsnprog.engine import اشتق, معنى, نبضات, استنتاج, عرض_المثال

التعليمات = (
    "لغة لسن — مترجم أولي\n"
    "الأوامر:\n"
    "  اشتق <كلمة>             تحليل الجذر واللاحقة والمعنى\n"
    "  معنى <كلمة> في <سياق>   اختيار المعنى الأنسب حسب السياق\n"
    "  نبض <نص>                ترميز النص إلى نبضات (هوفمان)\n"
    "  استنتاج                  عرض الاستنتاج الرمزي\n"
    "  مثال                     عرض الأمثلة التأسيسية كاملة\n"
    "  خروج                     إنهاء\n"
)


def الرئيسية():
    print(التعليمات)
    while True:
        try:
            سطر = input("لسن> ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break
        if not سطر:
            continue
        if سطر in ("خروج", "exit", "quit"):
            break
        if سطر == "مثال":
            print(عرض_المثال())
            continue
        if سطر == "استنتاج":
            print("\n".join(استنتاج()))
            continue
        أجزاء = سطر.split(" ", 1)
        الأمر = أجزاء[0]
        الباقي = أجزاء[1] if len(أجزاء) > 1 else ""

        if الأمر == "اشتق":
            ن = اشتق(الباقي)
            if ن:
                print(f"{ن['الكلمة']} ← جذر «{ن['الجذر']}» ({ن['معنى الجذر']})")
                print(f"    + لاحقة «{ن['اللاحقة']}» ({ن['معنى اللاحقة']})")
                print(f"    ⇒ {ن['المعنى']}")
            else:
                print(f"لا أعرف الكلمة «{الباقي}» بعد.")
        elif الأمر == "معنى":
            if " في " in الباقي:
                الكلمة, السياق = الباقي.split(" في ", 1)
            else:
                الكلمة, السياق = الباقي, ""
            ن = معنى(الكلمة, السياق)
            if ن:
                print(f"«{الكلمة}» معانيها: {'، '.join(ن['المعاني'])}")
                print(f"    في «{السياق or 'لا سياق'}» ⇒ {ن['المعنى المختار']}")
            else:
                print(f"لا أعرف معاني «{الكلمة}» بعد.")
        elif الأمر == "نبض":
            print(نبضات(الباقي))
        else:
            print("أمر غير معروف. اكتب «مثال» لرؤية العرض.")


if __name__ == "__main__":
    الرئيسية()
