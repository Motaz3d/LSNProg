import sys
import os
import collections

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lsnprog.alphabet import أبجدي
from lsnprog.corpus import جذر_تقريبي, صورة_رمزية_رقمية


def test_أبجدي_ابجد():
    # ا ب ج د = 1 + 2 + 3 + 4 = 10
    assert أبجدي("ابجد") == 10


def test_جذر_تقريبي_الرحمن():
    assert جذر_تقريبي("الرحمن") == "رحم"


def test_صورة_رمزية_رقمية_تربط_المعجم_بالقرآن():
    فهرس = {"رحم": {"التردد": 100, "الكلمات": collections.Counter({"رحمة": 60, "رحيم": 40})}}
    ص = صورة_رمزية_رقمية("رحم", فهرس)
    assert ص["الرمز"] == "رحم"
    assert "الرحمة" in ص["المعنى"]          # معنى من المعجم البسيط
    assert ص["التردد"] == 100                # تردد من القرآن
    assert ص["الأبجدي"] > 0
    assert ص["النبضي"] != ""


def test_جذر_غير_معروف_يأخذ_تسمية_مستخرج():
    فهرس = {"سجد": {"التردد": 5, "الكلمات": collections.Counter({"سجود": 5})}}
    ص = صورة_رمزية_رقمية("سجد", فهرس)
    assert "مستخرج" in ص["المعنى"]


def test_اربط_الجذور_بالمعجم_يميز_المعروف_والجديد():
    from lsnprog.corpus import اربط_الجذور_بالمعجم
    فهرس = {
        "رحم": {"التردد": 247, "الكلمات": collections.Counter({"رحمن": 157, "رحمه": 35})},
        "جدجد": {"التردد": 5, "الكلمات": collections.Counter({"جديد": 5})},
    }
    نتائج = اربط_الجذور_بالمعجم(فهرس, 40)
    قاموس = {ن["الجذر"]: ن for ن in نتائج}
    assert قاموس["رحم"]["معروف"] is True
    assert "الرحمة" in قاموس["رحم"]["المعنى"]
    assert قاموس["جدجد"]["معروف"] is False


def test_خريطة_الترافق_تكتشف_الجيران():
    from lsnprog.corpus import خريطة_الترافق
    آيات = ["لا خوف عليهم ولا هم يحزنون", "لا خوف عليهم ولا هم يحزنون", "إن الله معنا"]
    ترافق = خريطة_الترافق(آيات)
    assert ترافق["خوف"]["يحزنون"] == 2          # ترافقا مرتين
    assert ترافق["خوف"]["الله"] == 0            # لا يترافقان في نفس الآية


