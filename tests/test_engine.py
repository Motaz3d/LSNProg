import sys
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lsnprog.engine import اشتق, معنى, نبضات, استنتاج, قراءات, علاقة, رمزي_رقمي


def test_اشتقاق_قرآن():
    ن = اشتق("قرآن")
    assert ن["الجذر"] == "قرن"
    assert "الجمع" in ن["معنى الجذر"]


def test_رحمن_من_رحم_مع_لاحقة_ان():
    ن = اشتق("رحمن")
    assert ن["الجذر"] == "رحم"
    assert ن["اللاحقة"] == "ان"


def test_فرعون_من_فرع_مع_لاحقة_ون():
    ن = اشتق("فرعون")
    assert ن["الجذر"] == "فرع"
    assert ن["اللاحقة"] == "ون"


def test_شجرة_وشجار_من_شجر():
    assert اشتق("شجرة")["الجذر"] == "شجر"
    assert اشتق("شجار")["الجذر"] == "شجر"


def test_موسى_من_موس_القطع():
    ن = اشتق("موسى")
    assert ن["الجذر"] == "موس"
    assert "القطع" in ن["معنى الجذر"]


def test_عيسى_من_عيس_النقاء():
    ن = اشتق("عيسى")
    assert ن["الجذر"] == "عيس"
    assert "نقاء" in ن["معنى الجذر"] or "صفاء" in ن["معنى الجذر"]


def test_كلمة_من_كلم():
    ن = اشتق("كلمة")
    assert ن["الجذر"] == "كلم"


def test_المسيح_من_مسح():
    ن = اشتق("المسيح")
    assert ن["الجذر"] == "مسح"


def test_علاقة_عيسى_كلمة_الله():
    ن = علاقة("عيسى كلمة الله")
    assert "عيسى" in ن and "كلمة" in ن


def test_رمزي_رقمي_يدمج_الرمز_والرقم():
    ن = رمزي_رقمي("شجرة")
    assert ن["الرمز"] == "شجرة"
    assert ن["الرقم"] != ""


def test_علاقة_موسى_يقطع_فرعون():
    ن = علاقة("موسى يقطع فرعون")
    assert "موسى" in ن and "فرعون" in ن


def test_معنى_يد_في_سياق_القوة():
    ن = معنى("يد", "يد الله فوق أيديهم")
    assert "قوة" in ن["المعنى المختار"]


def test_معنى_فوق_في_سياق_السيطرة():
    ن = معنى("فوق", "يد الله فوق أيديهم")
    assert "سيطرة" in ن["المعنى المختار"] or "تعال" in ن["المعنى المختار"]


def test_نبضات_قرآن():
    # ق ر ا ن = 111110 10101 00 1110
    assert نبضات("قرآن") == "111110 10101 00 1110"


def test_استنتاج():
    assert len(استنتاج()) == 4


def test_قراءات_يوم_الدين():
    ن = قراءات("يوم الدين")
    assert ن is not None
    assert "ملك" in ن[0]
    assert any("مالِك" in س for س in ن)


