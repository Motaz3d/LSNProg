import sys
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lsnprog.neural import بناء_الشبكة


def test_السلطان_ليس_الملك():
    ش = بناء_الشبكة()
    assert "سلطان" in ش.العقد
    assert "ملك" in ش.العقد
    assert any(أ == "سلطان" and ب == "جبر" for أ, _, ب, _ in ش.الروابط)


def test_السلطان_جوهره_القوة_والملك_جوهره_الملكية():
    ش = بناء_الشبكة()
    روابط = [(أ, ب) for أ, _, ب, _ in ش.الروابط]
    assert ("سلطان", "القوة القاهرة") in روابط
    assert ("ملك", "الملكية") in روابط


def test_استعلام_من_يقطع_فرعون_يصل_إلى_موسى():
    ش = بناء_الشبكة()
