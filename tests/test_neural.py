def test_تعلم_جذر_ورابط_جديدين():
    from lsnprog.neural import علّم_جذر, علّم_رابط
    ش = بناء_الشبكة()
    # قبل التعليم: لا يعرف «الدنيا»
    assert "الدنيا" not in ش.العقد
    # التعليم من مثال قرآني
    علّم_جذر(ش, "دنو", "الدنو والقرب", [("الدنيا", "الحياة الدانية القريبة")])
    علّم_جذر(ش, "أخر", "التأخر والبعد", [("الآخرة", "الحياة المتأخرة")])
    علّم_رابط(ش, "الدنيا", "تقابل", "الآخرة")
    # بعد التعليم: يعرف ويستنتج
    أسماء = [اسم for اسم, _, _ in ش.استعلام("ما معنى الدنيا")]
    assert "الدنيا" in أسماء
    assert "دنو" in أسماء


