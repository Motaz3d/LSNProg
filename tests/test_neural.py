def test_التعلم_يعمل_لمفهوم_جديد():
    from lsnprog.neural import علّم_جذر, علّم_رابط
    ش = بناء_الشبكة()
    assert "نجم" not in ش.العقد
    علّم_جذر(ش, "نجم", "النجم والظهور", [("نجم", "الكوكب المضيء")])
    علّم_رابط(ش, "نجم", "في", "السماء", 1.0)
    أسماء = [اسم for اسم, _, _ in ش.استعلام("ما معنى نجم")]
    assert "نجم" in أسماء


