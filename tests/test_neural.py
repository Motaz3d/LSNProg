import sys
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lsnprog.neural import بناء_الشبكة


def test_السلطان_ليس_الملك():
    ش = بناء_الشبكة()
    assert "سلطان" in ش.العقد
    assert "ملك" in ش.العقد
    # سلطان يرتبط بالجبر، لا يساوي الملك
    assert any(أ == "سلطان" and ب == "جبر" for أ, _, ب, _ in ش.الروابط)


def test_استعلام_من_يقطع_فرعون_يصل_إلى_موسى():
    ش = بناء_الشبكة()
    نتائج = ش.استعلام("من يقطع فرعون")
    أسماء = [اسم for اسم, _, _ in نتائج]
    assert "موسى" in أسماء
    assert "فرعون" in أسماء


def test_استعلام_عيسى_يصل_إلى_كلمة_الله():
    ش = بناء_الشبكة()
    نتائج = ش.استعلام("ما معنى عيسى")
    أسماء = [اسم for اسم, _, _ in نتائج]
    assert "عيسى" in أسماء
    assert "كلمة الله" in أسماء or "المسيح" in أسماء


def test_استعلام_يد_الله_فوق_يصل_إلى_السيطرة():
    ش = بناء_الشبكة()
    نتائج = ش.استعلام("يد الله فوق أيديهم")
    أسماء = [اسم for اسم, _, _ in نتائج]
    assert "السيطرة والتعالي والقهر" in أسماء


